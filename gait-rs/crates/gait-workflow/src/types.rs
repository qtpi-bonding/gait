//! TypeScript declaration generation for script workflows (`gait workflow
//! types`).
//!
//! Every option/result interface and string-enum union in the emitted
//! `gait.d.ts` is GENERATED from `schemars::schema_for!` of the step structs
//! in [`crate::step`] — no struct's fields are ever copied by hand. A small
//! renderer walks each root schema and maps it to TypeScript:
//!
//! - object properties → interface members (schema order, deterministic);
//! - `required` absence (Option fields carry `#[serde(default)]`) → optional
//!   `?` member;
//! - a `null` variant in a property's `anyOf` → `T | null` for required
//!   members;
//! - `$ref`/`definitions` → the referenced type's name (all referenced types
//!   are emitted by this module too);
//! - arrays → `T[]`, maps → `Record<string, T>`;
//! - integers/numbers → `number`, booleans → `boolean`;
//! - string enums → `"a" | "b"` unions;
//! - free JSON values (`serde_json::Value`) → `unknown`;
//! - schema `description`s (from Rust doc comments) → `/** ... */` doc
//!   comments.
//!
//! The hand-written host-API block at the end of the file mirrors
//! `crates/gait-workflow/src/prelude.js` exactly; it is appended after the
//! generated types.

use schemars::schema::SingleOrVec;
use schemars::schema::{InstanceType, ObjectValidation, RootSchema, Schema, SchemaObject};
use schemars::schema_for;

/// File name the generated declarations are written as, inside the
/// gait dir's `workflows/` directory.
pub const DTS_FILE_NAME: &str = "gait.d.ts";

/// The generated `gait.d.ts` content: generated types, then the hand-written
/// host API declaration block.
pub fn render_dts() -> String {
    let mut out = String::new();
    out.push_str("// Generated by `gait workflow types`. Do not edit.\n");
    out.push_str("//\n");
    out.push_str("// TypeScript declarations for workflow scripts. Enable checking by adding\n");
    out.push_str("// `// @ts-check` at the top of your `gait workflow` script (a global script\n");
    out.push_str("// file — no import/export). Option fields are optional properties; a\n");
    out.push_str("// required result field whose Rust type is an Option is `T | null`.\n\n");

    for (name, root) in generated_types() {
        out.push_str(&render_root(name, &root));
        out.push('\n');
    }
    out.push_str(HOST_API);
    out
}

// ── Schema walking ──────────────────────────────────────────────────────────

/// All generated option/result types, in the fixed order they are emitted.
fn generated_types() -> Vec<(&'static str, RootSchema)> {
    macro_rules! types {
        ($($t:ty),+ $(,)?) => {
            vec![$((stringify!($t), schema_for!($t))),+]
        };
    }
    use crate::step::{
        Backoff, ConfigOpts, GateOpts, OnFail, RecordCommandOpts, RecordOpts, RetryOpts, ShellOpts,
        StepHooks, StepResult, TurnOpts,
    };
    types![
        ConfigOpts,
        RecordOpts,
        RecordCommandOpts,
        RetryOpts,
        Backoff,
        OnFail,
        StepHooks,
        TurnOpts,
        ShellOpts,
        GateOpts,
        StepResult,
    ]
}

/// Whether the schema is exactly `null`.
fn is_null_schema(schema: &Schema) -> bool {
    match schema {
        Schema::Object(o) => o
            .instance_type
            .as_ref()
            .map(|set| match set {
                SingleOrVec::Single(t) => **t == InstanceType::Null,
                SingleOrVec::Vec(v) => v.len() == 1 && v[0] == InstanceType::Null,
            })
            .unwrap_or(false),
        _ => false,
    }
}

/// The schema's doc-comment description, wherever the renderer put it.
fn description_of(schema: &SchemaObject) -> Option<&String> {
    schema
        .metadata
        .as_ref()
        .and_then(|m| m.description.as_ref())
}

/// Map one property schema to its TypeScript type. The bool is `true` when a
/// `null` variant must be appended (`T | null`) — required Option fields.
fn ts_type(schema: &Schema) -> (String, bool) {
    match schema {
        Schema::Bool(true) => ("unknown".to_string(), false),
        Schema::Bool(false) => ("never".to_string(), false),
        Schema::Object(obj) => ts_object(obj),
    }
}

/// Map one object schema to its TypeScript type.
fn ts_object(obj: &SchemaObject) -> (String, bool) {
    {
        // schemars 0.8 wraps a `$ref` that carries a default or
        // description in `allOf: [ { $ref } ]`.
        if let Some(all_of) = obj.subschemas.as_ref().and_then(|s| s.all_of.as_ref()) {
            if all_of.len() == 1 {
                return ts_type(&all_of[0]);
            }
        }
        if let Some(reference) = &obj.reference {
            let name = reference.rsplit('/').next().unwrap_or(reference);
            return (name.to_string(), false);
        }
        // Option<T> via anyOf with exactly one null variant.
        if let Some(any_of) = obj.subschemas.as_ref().and_then(|s| s.any_of.as_ref()) {
            let non_null: Vec<&Schema> = any_of.iter().filter(|s| !is_null_schema(s)).collect();
            if any_of.len() >= 2 && non_null.len() == any_of.len() - 1 {
                let (t, _) = ts_type(non_null[0]);
                return (t, true);
            }
        }
        if let Some(values) = &obj.enum_values {
            let variants: Vec<String> = values.iter().map(serde_json::Value::to_string).collect();
            return (variants.join(" | "), false);
        }
        if let Some(array) = &obj.array {
            match &array.items {
                Some(SingleOrVec::Single(items)) => match items.as_ref() {
                    Schema::Object(obj) => {
                        let (t, _) = ts_object(obj);
                        return (format!("{t}[]"), false);
                    }
                    _ => return ("unknown[]".to_string(), false),
                },
                Some(SingleOrVec::Vec(items)) => {
                    let parts: Vec<String> = items.iter().map(|s| ts_type(s).0).collect();
                    return (format!("[{}]", parts.join(", ")), false);
                }
                None => return ("unknown[]".to_string(), false),
            }
        }
        if let Some(object) = &obj.object {
            match &object.additional_properties {
                Some(additional) => {
                    let (t, _) = ts_type(additional.as_ref());
                    return (format!("Record<string, {t}>"), false);
                }
                _ => return ("Record<string, unknown>".to_string(), false),
            }
        }
        let types: Vec<InstanceType> = obj
            .instance_type
            .as_ref()
            .map(|set| match set {
                SingleOrVec::Single(t) => vec![**t],
                SingleOrVec::Vec(v) => v.to_vec(),
            })
            .unwrap_or_default();
        // schemars 0.8 renders `Option<T>` as `["T", "null"]`.
        let nullable = types.len() > 1 && types.contains(&InstanceType::Null);
        if types.contains(&InstanceType::Integer) || types.contains(&InstanceType::Number) {
            ("number".to_string(), nullable)
        } else if types.contains(&InstanceType::Boolean) {
            ("boolean".to_string(), nullable)
        } else if types.contains(&InstanceType::String) {
            ("string".to_string(), nullable)
        } else {
            ("unknown".to_string(), false)
        }
    }
}

/// Render one root schema: an interface for structs, a `type X = ...` union
/// for string enums.
fn render_root(name: &str, root: &RootSchema) -> String {
    if let Some(values) = &root.schema.enum_values {
        let mut out = String::new();
        if let Some(doc) = description_of(&root.schema) {
            out.push_str(&doc_comment(doc, ""));
        }
        let variants: Vec<String> = values.iter().map(serde_json::Value::to_string).collect();
        out.push_str(&format!("type {name} = {};\n", variants.join(" | ")));
        return out;
    }
    let validation = match &root.schema.object {
        Some(validation) => validation,
        None => {
            // Not an object and not a known enum: emit an opaque alias so the
            // file stays valid TypeScript.
            return format!("type {name} = unknown;\n");
        }
    };
    render_interface(name, root, validation)
}

/// Render one struct's root schema as an interface declaration.
fn render_interface(name: &str, root: &RootSchema, validation: &ObjectValidation) -> String {
    let mut out = String::new();
    if let Some(doc) = description_of(&root.schema) {
        out.push_str(&doc_comment(doc, ""));
    }
    out.push_str(&format!("interface {name} {{\n"));
    // A result type: every property is emitted as required, except `error`.
    let is_result = name == "StepResult";
    for (property, schema) in &validation.properties {
        let (ty, nullable) = ts_type(schema);
        let obj = match schema {
            Schema::Object(obj) => Some(obj),
            Schema::Bool(_) => None,
        };
        let required = (is_result && property != "error") || validation.required.contains(property);
        let optional = if required { "" } else { "?" };
        let ty = if (required || (is_result && property != "error")) && nullable {
            format!("{ty} | null")
        } else {
            ty
        };
        if let Some(doc) = obj.and_then(description_of) {
            out.push_str(&doc_comment(doc, "    "));
        }
        out.push_str(&format!("    {property}{optional}: {ty};\n"));
    }
    out.push_str("}\n");
    out
}

/// A schema `description` as a `/** ... */` doc comment (one line per
/// paragraph line, indented to member level).
fn doc_comment(text: &str, indent: &str) -> String {
    let mut out = String::new();
    for line in text.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            out.push_str(&format!("{indent} *\n"));
        } else {
            out.push_str(&format!("{indent} * {line}\n"));
        }
    }
    format!("{indent}/**\n{out}{indent} */\n")
}

// ── Host API (hand-written; must match src/prelude.js exactly) ─────────────

/// The fixed declaration block for the workflow host object. Kept in sync
/// by hand with `crates/gait-workflow/src/prelude.js`; the golden test pins
/// the whole file.
const HOST_API: &str = r#"// ── Host API ────────────────────────────────────────────────────────────────
// Mirrors the workflow prelude (gait.wf) exactly. `run` is the workflow run
// context the script was launched with.

declare namespace gait {
    namespace wf {
        /** The current run: its id, the CLI args after the workflow name, the
         * codebase directory and the gait workspace directory. */
        const run: { runId: string; args: string[]; codebase: string; workspace: string };

        /** Configure the workflow. Must be called (and awaited) before any
         * other step; may only be called once. */
        function config(opts: ConfigOpts): Promise<{ runId: string }>;

        /** Run a prompt (model turn) step. A `prompt`-less turn suspends the
         * run for interactive input. */
        function turn(opts: TurnOpts): Promise<StepResult>;

        /**
         * Run a shell step. `sh` returns no `id`, so a shell step spreads it:
         *
         *     gait.wf.shell({ id: "t", ...gait.wf.sh`cargo test ${name}` })
         */
        function shell(opts: ShellOpts): Promise<StepResult>;

        /** Suspend the run for human approval. Resolves to null once the run
         * is continued past the gate. */
        function gate(opts: GateOpts): Promise<null | { error: string }>;

        /** The current unix time in milliseconds (journaled, so replays return
         * the same value). Deterministic alternative to `Date.now()`. */
        function now(): Promise<number>;

        /** A pseudo-random number in [0, 1) (journaled, so replays return the
         * same value). Deterministic alternative to `Math.random()`. */
        function random(): Promise<number>;

        /** Tagged template for shell steps: interpolations become
         * `"$GAIT_ARG_<i>"` markers in the script text and entries in `env`;
         * values are never spliced into the script text. */
        function sh(
            strings: TemplateStringsArray,
            ...values: unknown[]
        ): { script: string; env: Record<string, string> };
    }
}
"#;

// ── Tests ───────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dts_starts_with_the_generated_banner() {
        let dts = render_dts();
        assert!(dts.starts_with("// Generated by `gait workflow types`. Do not edit.\n"));
        assert!(dts.contains("@ts-check"));
        assert!(!dts.contains("export "), "the file is a global script");
    }

    #[test]
    fn dts_declares_every_option_type() {
        let dts = render_dts();
        for name in [
            "ConfigOpts",
            "RecordOpts",
            "RecordCommandOpts",
            "RetryOpts",
            "Backoff",
            "OnFail",
            "StepHooks",
            "TurnOpts",
            "ShellOpts",
            "GateOpts",
            "StepResult",
        ] {
            assert!(
                dts.contains(&format!("interface {name} {{"))
                    || dts.contains(&format!("type {name} =")),
                "{name} missing from the generated d.ts"
            );
        }
    }

    #[test]
    fn step_result_is_required_and_nullable_per_option() {
        let dts = render_dts();
        let body = dts
            .split("interface StepResult {")
            .nth(1)
            .expect("StepResult present")
            .split('}')
            .next()
            .unwrap();
        assert!(body.contains("    output: string;\n"));
        assert!(body.contains("    exit: number | null;\n"));
        assert!(body.contains("    json: unknown;\n"), "{body}");
        assert!(body.contains("    sessionId: string | null;\n"));
        assert!(body.contains("    error?: string;\n"), "{body}");
    }

    #[test]
    fn enums_render_as_string_unions() {
        let dts = render_dts();
        assert!(
            dts.contains("type Backoff = \"linear\" | \"exponential\";"),
            "{dts}"
        );
        assert!(
            dts.contains("type OnFail = \"throw\" | \"continue\";"),
            "{dts}"
        );
    }

    #[test]
    fn option_fields_are_optional_properties() {
        let dts = render_dts();
        let body = dts
            .split("interface TurnOpts {")
            .nth(1)
            .expect("TurnOpts present")
            .split('}')
            .next()
            .unwrap();
        assert!(body.contains("    id: string;\n"), "{body}");
        assert!(body.contains("    prompt?: string;\n"), "{body}");
        assert!(body.contains("    retry?: RetryOpts;\n"), "{body}");
    }

    #[test]
    fn host_api_mirrors_the_prelude() {
        let dts = render_dts();
        for needle in [
            "const run: { runId: string; args: string[]; codebase: string; workspace: string };",
            "function config(opts: ConfigOpts): Promise<{ runId: string }>;",
            "function turn(opts: TurnOpts): Promise<StepResult>;",
            "function shell(opts: ShellOpts): Promise<StepResult>;",
            "function gate(opts: GateOpts): Promise<null | { error: string }>;",
            "function now(): Promise<number>;",
            "function random(): Promise<number>;",
            "function sh(",
            "...gait.wf.sh`cargo test ${name}`",
        ] {
            assert!(dts.contains(needle), "host API missing: {needle}");
        }
    }
}
